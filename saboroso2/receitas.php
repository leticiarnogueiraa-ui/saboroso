function buscarReceitaPorId($id)
{
    global $receitas;

    foreach ($receitas as $receita) {
        if ((int) $receita['id'] === (int) $id) {
            return $receita;
        }
    }

    return null;
}

function listarReceitasPorCategoria($categoria)
{
    global $receitas;

    return array_values(array_filter($receitas, function ($receita) use ($categoria) {
        return $receita['categoria'] === $categoria;
    }));
}

function obterQuantidadeReceitas()
{
    global $receitas;

    return count($receitas);
}
